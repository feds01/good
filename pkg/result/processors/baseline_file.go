const (
	baselineFileVersion = 2

	baselineFileHeader = "# Generated by `good baseline`. Fix issues and run `good baseline --prune`; do not add entries by hand.\n"

	baselineSourceMaxRunes = 100
)

var baselineHashPattern = regexp.MustCompile(`^[0-9a-f]{` + strconv.Itoa(baselineHashLength) + `}$`)

// baselineKey identifies the issues of one file that the baseline treats as the same.
type baselineKey struct {
	Linter  string
	Hash    string
	Message string
}

func compareBaselineKeys(a, b baselineKey) int {
	return cmp.Or(
		cmp.Compare(a.Linter, b.Linter),
		cmp.Compare(a.Message, b.Message),
		cmp.Compare(a.Hash, b.Hash),
	)
}

type baselineEntry struct {
	baselineKey

	Count  int
	Source string

	// Set while matching: the issues that used the entry unchanged or that took it over.
	exact      int
	moved      int
	liveSource string
}

// remaining is the part of the entry that no issue of this run used.
func (e *baselineEntry) remaining() int {
	return e.Count - e.exact - e.moved
}

// baselineContent maps a path (relative to the config base path, with forward slashes) to its entries.
type baselineContent map[string]map[baselineKey]*baselineEntry

func (c baselineContent) add(path string, entry *baselineEntry) {
	if entry.Count <= 0 {
		return
	}

	entries := c[path]
	if entries == nil {
		entries = map[baselineKey]*baselineEntry{}
		c[path] = entries
	}

	existing, ok := entries[entry.baselineKey]
	if !ok {
		copied := *entry
		entries[entry.baselineKey] = &copied

		return
	}

	existing.Count += entry.Count

	if existing.Source == "" {
		existing.Source = entry.Source
	}
}

// sortedEntries returns the entries of a path in file order.
func (c baselineContent) sortedEntries(path string) []*baselineEntry {
	entries := slices.Collect(maps.Values(c[path]))

	slices.SortFunc(entries, func(a, b *baselineEntry) int {
		return compareBaselineKeys(a.baselineKey, b.baselineKey)
	})

	return entries
}

type baselineEntryDTO struct {
	Linter  string `toml:"linter"`
	Hash    string `toml:"hash"`
	Count   any    `toml:"count"`
	Message string `toml:"message"`
	Source  string `toml:"source"`
}

type baselineFileDTO struct {
	Entries []baselineEntryDTO `toml:"entries"`
}

func readBaselineFile(path string) (baselineContent, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("can't read baseline %s: %w", path, err)
	}

	content, err := decodeBaseline(data)
	if err != nil {
		return nil, fmt.Errorf("can't parse baseline %s: %w", path, err)
	}

	return content, nil
}

func decodeBaseline(data []byte) (baselineContent, error) {
	var raw map[string]any

	err := toml.Unmarshal(data, &raw)
	if err != nil {
		return nil, err
	}

	version, ok := raw["version"].(int64)
	if !ok {
		return nil, errors.New("missing `version`")
	}

	if version == 1 {
		return nil, errors.New("baseline format version 1 is outdated (its fingerprints ignore the surrounding lines): " +
			"delete the file and record it again with the baseline command")
	}

	if version != baselineFileVersion {
		return nil, fmt.Errorf("unsupported baseline version %d (this build reads version %d)", version, baselineFileVersion)
	}

	delete(raw, "version")

	content := baselineContent{}

	for _, path := range slices.Sorted(maps.Keys(raw)) {
		err := decodeBaselineFile(content, path, raw[path])
		if err != nil {
			return nil, fmt.Errorf("%q: %w", path, err)
		}
	}

	return content, nil
}

func decodeBaselineFile(content baselineContent, path string, table any) error {
	_, isTable := table.(map[string]any)
	if !isTable {
		return fmt.Errorf("expected a table with `entries`, got %T", table)
	}

	// Re-encoding the table lets the strict decoder report unknown keys.
	data, err := toml.Marshal(table)
	if err != nil {
		return err
	}

	var dto baselineFileDTO

	decoder := toml.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()

	err = decoder.Decode(&dto)
	if err != nil {
		var strictErr *toml.StrictMissingError
		if errors.As(err, &strictErr) {
			return fmt.Errorf("unknown key: %s", strictErr.String())
		}

		return err
	}

	for index, entryDTO := range dto.Entries {
		if entryDTO.Linter == "" {
			return fmt.Errorf("entry %d: no `linter`", index+1)
		}

		if entryDTO.Hash != "" && !baselineHashPattern.MatchString(entryDTO.Hash) {
			return fmt.Errorf("entry %d (%s: %s): invalid `hash` %q", index+1, entryDTO.Linter, entryDTO.Message, entryDTO.Hash)
		}

		count, err := decodeBaselineCount(entryDTO.Count)
		if err != nil {
			return fmt.Errorf("entry %d (%s: %s): %w", index+1, entryDTO.Linter, entryDTO.Message, err)
		}

		content.add(path, &baselineEntry{
			baselineKey: baselineKey{Linter: entryDTO.Linter, Hash: entryDTO.Hash, Message: entryDTO.Message},
			Count:       count,
			Source:      entryDTO.Source,
		})
	}

	return nil
}

func decodeBaselineCount(value any) (int, error) {
	if value == nil {
		return 1, nil
	}

	count, ok := value.(int64)
	if !ok {
		return 0, fmt.Errorf("invalid `count` %v, it must be an integer", value)
	}

	if count < 1 {
		return 0, fmt.Errorf("invalid `count` %d, it must be at least 1", count)
	}

	return int(count), nil
}

// encodeBaseline writes the content in a byte-stable form: files by path, entries by linter, message and hash,
// one entry per line, no line numbers.
func encodeBaseline(content baselineContent) []byte {
	var buf bytes.Buffer

	buf.WriteString(baselineFileHeader)
	fmt.Fprintf(&buf, "version = %d\n", baselineFileVersion)

	paths := slices.Sorted(maps.Keys(content))

	for _, path := range paths {
		entries := content.sortedEntries(path)
		if len(entries) == 0 {
			continue
		}

		buf.WriteString("\n[" + quoteTOML(path) + "]\nentries = [\n")

		for _, entry := range entries {
			buf.WriteString("  " + encodeBaselineEntry(entry) + ",\n")
		}

		buf.WriteString("]\n")
	}

	return buf.Bytes()
}

func encodeBaselineEntry(entry *baselineEntry) string {
	fields := []string{"linter = " + quoteTOML(entry.Linter)}

	if entry.Hash != "" {
		fields = append(fields, "hash = "+quoteTOML(entry.Hash))
	}

	if entry.Count > 1 {
		fields = append(fields, "count = "+strconv.Itoa(entry.Count))
	}

	fields = append(fields, "message = "+quoteTOML(entry.Message))

	if entry.Source != "" {
		fields = append(fields, "source = "+quoteTOML(truncateRunes(entry.Source, baselineSourceMaxRunes)))
	}

	return "{ " + strings.Join(fields, ", ") + " }"
}

func truncateRunes(s string, maxRunes int) string {
	if utf8.RuneCountInString(s) <= maxRunes {
		return s
	}

	return string([]rune(s)[:maxRunes])
}

// quoteTOML renders a TOML basic string.
func quoteTOML(s string) string {
	var b strings.Builder

	b.WriteByte('"')

	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}

	b.WriteByte('"')

	return b.String()
}

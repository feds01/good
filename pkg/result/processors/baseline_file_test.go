package processors

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const baselineGolden = `# Generated by ` + "`good baseline`" + `. Fix issues and run ` + "`good baseline --prune`" + `; do not add entries by hand.
version = 1

["internal/api/handler.go"]
entries = [
  { linter = "errcheck", hash = "3f9a2c1e", count = 2, message = "Error return value of ` + "`rows.Close`" + ` is not checked" },
  { linter = "gosec", hash = "a07c55d2", message = "G304: Potential file inclusion via variable", source = "f, err := os.Open(path)" },
]

["z.go"]
entries = [
  { linter = "gomoddirectives", message = "quote \" and backslash \\ and tab \t" },
]
`

func TestBaselineFile_goldenRoundTrip(t *testing.T) {
	content, err := decodeBaseline([]byte(baselineGolden))
	require.NoError(t, err)

	assert.Equal(t, 2, content["internal/api/handler.go"][baselineKey{
		Linter: "errcheck", Hash: "3f9a2c1e", Message: "Error return value of `rows.Close` is not checked",
	}].Count)

	assert.Equal(t, baselineGolden, string(encodeBaseline(content)))
}

func TestBaselineFile_encodingIsIndependentOfInsertionOrder(t *testing.T) {
	entries := []struct {
		path string
		key  baselineKey
	}{
		{"b.go", baselineKey{Linter: "revive", Hash: "00000002", Message: "m"}},
		{"a.go", baselineKey{Linter: "revive", Hash: "00000001", Message: "m"}},
		{"a.go", baselineKey{Linter: "errcheck", Hash: "00000009", Message: "z"}},
		{"a.go", baselineKey{Linter: "errcheck", Hash: "00000009", Message: "a"}},
	}

	forward := baselineContent{}
	for _, entry := range entries {
		forward.add(entry.path, &baselineEntry{baselineKey: entry.key, Count: 1})
	}

	backward := baselineContent{}
	for index := len(entries) - 1; index >= 0; index-- {
		backward.add(entries[index].path, &baselineEntry{baselineKey: entries[index].key, Count: 1})
	}

	assert.Equal(t, string(encodeBaseline(forward)), string(encodeBaseline(backward)))

	text := string(encodeBaseline(forward))
	assert.Less(t, strings.Index(text, `["a.go"]`), strings.Index(text, `["b.go"]`))
	assert.Less(t, strings.Index(text, `message = "a"`), strings.Index(text, `message = "z"`))
}

func TestBaselineFile_mergesDuplicateEntries(t *testing.T) {
	content, err := decodeBaseline([]byte(`version = 1

["a.go"]
entries = [
  { linter = "x", hash = "00000001", message = "m" },
  { linter = "x", hash = "00000001", count = 2, message = "m" },
]
`))
	require.NoError(t, err)

	assert.Equal(t, 3, content["a.go"][baselineKey{Linter: "x", Hash: "00000001", Message: "m"}].Count)
}

func TestBaselineFile_decodeErrors(t *testing.T) {
	testCases := []struct {
		desc     string
		data     string
		contains string
	}{
		{desc: "no version", data: "[\"a.go\"]\nentries = []\n", contains: "version"},
		{desc: "future version", data: "version = 2\n", contains: "unsupported baseline version 2"},
		{desc: "unknown key", data: "version = 1\n[\"a.go\"]\nentries = [{ linter = \"x\", message = \"m\", line = 3 }]\n", contains: "line"},
		{desc: "unknown table key", data: "version = 1\n[\"a.go\"]\nitems = []\n", contains: "items"},
		{desc: "bad hash", data: "version = 1\n[\"a.go\"]\nentries = [{ linter = \"x\", hash = \"zz\", message = \"m\" }]\n", contains: "hash"},
		{desc: "no linter", data: "version = 1\n[\"a.go\"]\nentries = [{ message = \"m\" }]\n", contains: "linter"},
		{desc: "negative count", data: "version = 1\n[\"a.go\"]\nentries = [{ linter = \"x\", count = -1, message = \"m\" }]\n", contains: "count"},
		{desc: "not toml", data: "version = =", contains: ""},
	}

	for _, test := range testCases {
		t.Run(test.desc, func(t *testing.T) {
			_, err := decodeBaseline([]byte(test.data))

			require.Error(t, err)
			assert.Contains(t, err.Error(), test.contains)
		})
	}
}

func TestBaselineFile_longSourceIsTruncated(t *testing.T) {
	content := baselineContent{}
	content.add("a.go", &baselineEntry{
		baselineKey: baselineKey{Linter: "x", Message: "m"},
		Count:       1,
		Source:      strings.Repeat("é", 150),
	})

	text := string(encodeBaseline(content))

	assert.Contains(t, text, `source = "`+strings.Repeat("é", baselineSourceMaxRunes)+`"`)
}
